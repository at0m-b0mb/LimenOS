#!/usr/bin/env python3
"""Generate a 1-bit glyph atlas (ASCII 32..126) as a C header.

Rendered from DejaVu Sans Mono, whose changes are public domain and whose
Bitstream Vera base licence permits redistribution. Embedding a bitmap of it
keeps limen-say dependency-free on the device.
"""
from PIL import Image, ImageDraw, ImageFont
import sys

W, H = int(sys.argv[1]), int(sys.argv[2])
FONT = sys.argv[3]
OUT = sys.argv[4]

# size the face so its advance fills the cell width, not the cell height:
# DejaVu Sans Mono advances 0.602em
f = ImageFont.truetype(FONT, max(8, int(W / 0.602)))
rows = []
for c in range(32, 127):
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    d.text((0, -2), chr(c), font=f, fill=255)
    bits = []
    for y in range(H):
        v = 0
        for x in range(W):
            if img.getpixel((x, y)) > 110:
                v |= 1 << (W - 1 - x)
        bits.append(v)
    rows.append(bits)

with open(OUT, "w") as fh:
    fh.write("/* generated by mkfont.py - DejaVu Sans Mono bitmap atlas */\n")
    fh.write(f"#define GW {W}\n#define GH {H}\n")
    fh.write(f"static const unsigned short FONT[{len(rows)}][{H}] = {{\n")
    for i, bits in enumerate(rows):
        fh.write("  {" + ",".join("0x%04x" % b for b in bits) + "},\n")
    fh.write("};\n")
print(f"  atlas: {len(rows)} glyphs at {W}x{H} -> {OUT}")
